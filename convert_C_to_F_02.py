# BRIEF DESCRIPTION:  This program converts a temperature in Celsius to Fahrenheit
# using the formula F = C * 9/5 + 32.

def convert_C_to_F(celsius):
    fahrenheit = celsius * 9/5 + 32
    print(fahrenheit)


# Example
c = float(input("Enter temperature in Celsius: "))
convert_C_to_F(c)










